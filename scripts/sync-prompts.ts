// grokbot/BOTS.md is the single source of the crew's job descriptions.
// This writes lib/crew/prompts.generated.ts (API crew system prompts) and grokbot/setup/<agent>.md
// (paste-ready Grok Bot setup). Run: npm run sync-prompts. A test fails if they drift.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(__dirname, '..');
const md = readFileSync(path.join(root, 'grokbot/BOTS.md'), 'utf8');
const skill = readFileSync(path.join(root, 'grokbot/skills/afterhours-shift/SKILL.md'), 'utf8');

export function sections(src: string): Record<string, string> {
  const out: Record<string, string> = {};
  const parts = src.split(/^## /m).slice(1);
  for (const p of parts) {
    const [head, ...body] = p.split('\n');
    const id = head.match(/\(`(\w+)`/)?.[1] ?? (head.startsWith('Rules') ? 'rules' : head.trim());
    out[id] = `## ${head}\n${body.join('\n')}`.trim();
  }
  return out;
}

const s = sections(md);
const agents = ['rosa', 'vic', 'june', 'otto', 'lou', 'dot', 'fern'] as const;
const prompts = Object.fromEntries(agents.map((a) => [a, `${s.rules}\n\n${s[a]}`]));

